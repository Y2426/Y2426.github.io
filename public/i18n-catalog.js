export function translateCopy(source, locale) {
 if(locale!=='en'||!source)return source;
 const leading=source.match(/^\s*/)[0],trailing=source.match(/\s*$/)[0],key=source.trim();
 if(Object.hasOwn(en,key))return leading+en[key]+trailing;
 for(const [pattern,format]of patterns)if(pattern.test(key))return leading+key.replace(pattern,format)+trailing;
 if(key.includes(' · '))return leading+key.split(' · ').map(part=>translateCopy(part,locale)).join(' · ')+trailing;
 // Decorative arrows/checkmarks are separate from the semantic label.
 const decorated=key.match(/^([←↻✓●■◇＋✦▧▦♡◷]*\s*)(.+?)(\s*[↗→])?$/u);
 if(decorated&&Object.hasOwn(en,decorated[2]))return leading+decorated[1]+en[decorated[2]]+(decorated[3]||'')+trailing;
 return source;
}
